#!/usr/bin/env python3
"""Slice the Higgsfield-generated sheets in art/generated into a game atlas.

Usage:  python3 tools/build_assets.py
Writes: assets/sprites/atlas.webp + atlas.json, assets/img/*.webp
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art" / "generated"
OUT_SPR = ROOT / "assets" / "sprites"
OUT_IMG = ROOT / "assets" / "img"
OUT_SPR.mkdir(parents=True, exist_ok=True)
OUT_IMG.mkdir(parents=True, exist_ok=True)


def runs(mask_1d, min_len=4):
    out, start = [], None
    for i, v in enumerate(mask_1d):
        if v and start is None:
            start = i
        elif not v and start is not None:
            if i - start >= min_len:
                out.append((start, i))
            start = None
    if start is not None and len(mask_1d) - start >= min_len:
        out.append((start, len(mask_1d)))
    return out


def grid_cells(img):
    """Split a transparent sheet into cells using empty rows/columns."""
    a = np.array(img)[:, :, 3] > 16
    cells = []
    for y0, y1 in runs(a.sum(1) > 0, 20):
        row = []
        for x0, x1 in runs(a[y0:y1].sum(0) > 0, 4):
            sub = a[y0:y1, x0:x1]
            ys = np.where(sub.sum(1) > 0)[0]
            row.append((x0, y0 + ys[0], x1, y0 + ys[-1] + 1))
        cells.append(row)
    return cells


def crop_scale(img, box, scale, pad=2):
    x0, y0, x1, y1 = box
    c = img.crop((x0 - pad, y0 - pad, x1 + pad, y1 + pad))
    w, h = c.size
    return c.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)


sprites = {}
meta = {}

# ---- Pups: row 0 = Biscuit, row 1 = Marshmallow; cols = angry, hurt, ko, helmet
pups = Image.open(SRC / "pups.png").convert("RGBA")
PUP_SCALE = 0.56
names = ["biscuit", "marsh"]
states = ["angry", "hurt", "ko", "helmet"]
for r, row in enumerate(grid_cells(pups)):
    for c, box in enumerate(row):
        key = f"{names[r]}_{states[c]}"
        sprites[key] = crop_scale(pups, box, PUP_SCALE)
# Body width reference (angry pose) lets the game size every pose consistently.
for n in names:
    meta[n] = {"bodyW": sprites[f"{n}_angry"].size[0], "bodyH": sprites[f"{n}_angry"].size[1]}

# ---- Props: row 0 = small/medium/large foam balls, row 1 = slingshot
props = Image.open(SRC / "props.png").convert("RGBA")
prow = grid_cells(props)
BALL_SCALE = 0.46
for key, box in zip(["ball_s", "ball_m", "ball_l"], prow[0]):
    sprites[key] = crop_scale(props, box, BALL_SCALE)

SLING_SCALE = 0.58
sbox = prow[1][0]
sling = crop_scale(props, sbox, SLING_SCALE, pad=2)
sprites["sling"] = sling
# Locate the two dowel tops (anchor points for the rubber bands) in sprite space.
sa = np.array(sling)[:, :, 3] > 40
top_band = sa[: int(sa.shape[0] * 0.4)]
dowels = runs(top_band.sum(0) > 0, 3)
anchors = []
for x0, x1 in dowels[:2]:
    col = sa[:, x0:x1].sum(1)
    ty = int(np.where(col > 0)[0][0])
    anchors.append({"x": (x0 + x1) / 2 / sling.size[0], "y": (ty + 6) / sling.size[1]})
# The box's top surface (where the box meets the dowels' feet) - first opaque row at the far left column region
left = sa[:, int(sa.shape[1] * 0.05)]
box_top = int(np.where(left > 0)[0][0])
meta["sling"] = {"anchors": anchors, "boxTopLeftY": box_top / sling.size[1]}

# ---- Shelf-pack into a single atlas
order = sorted(sprites.items(), key=lambda kv: -kv[1].size[1])
ATLAS_W = 1600
x = y = shelf_h = 0
frames = {}
GAP = 4
for key, im in order:
    w, h = im.size
    if x + w > ATLAS_W:
        x, y, shelf_h = 0, y + shelf_h + GAP, 0
    frames[key] = {"x": x, "y": y, "w": w, "h": h}
    x += w + GAP
    shelf_h = max(shelf_h, h)
atlas_h = y + shelf_h
atlas = Image.new("RGBA", (ATLAS_W, atlas_h), (0, 0, 0, 0))
for key, im in sprites.items():
    f = frames[key]
    atlas.paste(im, (f["x"], f["y"]))
atlas.save(OUT_SPR / "atlas.webp", "WEBP", quality=92, method=6)
atlas.save(ROOT / "art" / "spritesheet.png", optimize=True)
atlas_data = {"w": ATLAS_W, "h": atlas_h, "frames": frames, "meta": meta}
(OUT_SPR / "atlas.json").write_text(json.dumps(atlas_data, indent=1))
# Also as a script so the game works from file:// (no fetch needed).
(ROOT / "js" / "atlas-data.js").write_text(
    "/* Generated by tools/build_assets.py - do not edit. */\n"
    "(function (r) { r.AP = r.AP || {}; r.AP.ATLAS = " + json.dumps(atlas_data) + "; })(typeof window !== 'undefined' ? window : globalThis);\n"
)

# ---- Logo
logo = Image.open(SRC / "logo.png").convert("RGBA")
bb = logo.getchannel("A").point(lambda v: 255 if v > 10 else 0).getbbox()
logo = logo.crop(bb)
logo.thumbnail((900, 900), Image.LANCZOS)
logo.save(OUT_IMG / "logo.webp", "WEBP", quality=92, method=6)

# ---- Gameplay background
bg = Image.open(SRC / "bg.png").convert("RGB")
bg.save(OUT_IMG / "bg.webp", "WEBP", quality=82, method=6)
bg.resize((bg.width // 2, bg.height // 2), Image.LANCZOS).save(OUT_IMG / "bg-sm.webp", "WEBP", quality=80, method=6)

print("atlas", ATLAS_W, "x", atlas_h)
print(json.dumps(meta, indent=1))
for k, f in frames.items():
    print(k, f)
